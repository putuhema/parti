/**
 * Builds src/lib/drillBank.ts: real puzzle positions where the very next move needs a given trick.
 * Run: npx tsx scripts/coach/build-drills.ts [puzzles]          (default 40000; takes several minutes)
 *      npx tsx scripts/coach/build-drills.ts [puzzles] --rare   (keeps the bank, tops up only RARE tricks)
 * Each saved position is [puzzle, solution, start]; the app disguises them with Sudoku symmetries.
 * Rare tricks may also be saved where they show up later in a lesson (after a few easier
 * eliminations); the app applies those first and opens the lesson at the rare trick.
 */
import { writeFileSync } from "node:fs";
import { generatePuzzle, mulberry32, setAt, type Difficulty } from "../../convex/lib/sudoku";
import { nextLesson, TECHNIQUES, type TechniqueId } from "../../src/lib/coach";
import { DRILL_BANK } from "../../src/lib/drillBank";
import { RARE } from "../../src/lib/drills";

const PER_TRICK = 12;
const TOTAL = Number(process.argv[2] ?? 40000);
const rareOnly = process.argv.includes("--rare");
const bank = Object.fromEntries((Object.keys(TECHNIQUES) as TechniqueId[]).map((t) => [t, [] as [string, string, string][]])) as Record<TechniqueId, [string, string, string][]>;
if (rareOnly) for (const t of Object.keys(bank) as TechniqueId[]) bank[t] = [...(DRILL_BANK[t] ?? [])];
const wanted = (t: TechniqueId) => bank[t].length < PER_TRICK && (!rareOnly || RARE.includes(t));
const full = () => (Object.keys(bank) as TechniqueId[]).every((t) => !wanted(t));
const t0 = Date.now();

for (let k = 0; k < TOTAL && !full(); k++) {
  const level: Difficulty = k % 3 === 0 ? "hard" : "expert";
  const { puzzle, solution } = generatePuzzle(level, mulberry32(900_000 + k));
  let values = puzzle;
  const taken = new Set<TechniqueId>(); // one position per trick per puzzle, for variety
  for (let guard = 0; guard < 81 && values.includes("0"); guard++) {
    const lesson = nextLesson(values, new Set());
    if (!lesson.stuck) {
      // A trick counts if it's the first step, or (for rare tricks) any step of the lesson.
      const here = lesson.steps.map((s, k) => ({ t: s.technique, k })).filter(({ t, k }) => k === 0 || RARE.includes(t));
      for (const { t } of here) {
        if (taken.has(t) || !wanted(t)) continue;
        bank[t].push([puzzle, solution, values]);
        taken.add(t);
      }
    }
    const last = lesson.steps.at(-1);
    if (lesson.stuck || !last?.place) break;
    values = setAt(values, last.place.cell, String(last.place.digit));
  }
  if (k % 2000 === 0) console.log(`${k} puzzles, ${Math.round((Date.now() - t0) / 1000)}s:`, (Object.keys(bank) as TechniqueId[]).filter(wanted).map((t) => `${t}:${bank[t].length}`).join(" ") || "all full");
}

const body = Object.entries(bank).map(([t, rows]) => `  ${t}: [\n${rows.map((r) => `    ${JSON.stringify(r)},`).join("\n")}\n  ],`).join("\n");
writeFileSync("src/lib/drillBank.ts", `// Generated by scripts/coach/build-drills.ts. Do not edit by hand.
// Real positions where the next move needs each trick: [puzzle, solution, start].
import type { TechniqueId } from "./coach";

export const DRILL_BANK: Record<TechniqueId, [string, string, string][]> = {
${body}
};
`);
console.log("done:", Object.entries(bank).map(([t, b]) => `${t}:${b.length}`).join(" "));
